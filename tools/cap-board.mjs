/*
cap-board.mjs -- H26.6's move 9 (dev/design/components/PAN-ZOOM.md section 4, PZ11; appendix A, move 9) -- THE BOARD AT EVERY CAP, for
the lab's pan measure: generated here, written into lab/seeds.json as the board `caps`, which the director opens by name
(`?seed=caps`), and held equal to this generator by tests/cap-board.test.js.

PZ11 asks a board "at every cap at once -- 527 anchors, 576 zones, 2,000 links, 4,000 pipes, 2,000 groups -- in run mode with its
spawners armed", panned at 3x on the Chromebook. Built, on the old frame the editor still holds until move 11:
  anchors   527, every position of the device grid within the old frame -- 31 by 17 at 60 -- a waypoint wherever the column and row
            sum to a multiple of 5 (106), a device elsewhere (421), each waypoint an armed spawner on the first link it ends (B246)
  zones     576: a zone of one square at each of the 527 corners whose square lies within the frame, and 49 of two squares by two
  links     2,000 between anchors one step apart -- across, down, and both diagonals -- and then two across, each pair once
  pipes     4,000 hand pipes, between anchors at the links' steps and then longer ones, each pair once (one pipe per pair, N2)
  groups    263, each two devices or waypoints in id order -- the most a document with 527 anchors can hold: a group holds nodes
            alone (B83), at least two (B85), and a node belongs to one group (B82), so 2,000 groups would need 4,000 anchors
            (PAN-ZOOM.md appendix B, move 9, E10)
and opens in run mode (`mode`), so the spawners emit at once.

Usage: node tools/cap-board.mjs --write   the board written into lab/seeds.json as `caps`, every other board kept
       node tools/cap-board.mjs --check   exit 1 when lab/seeds.json's `caps` is not this generator's
*/
import fs from 'node:fs';

const PITCH = 60;
const COLS = 31, ROWS = 17;              // the device grid within the old frame: x -900 to 900, y -480 to 480
const SPAWN = { interval: 500, speed: 3, kind: 'packet', since: 1790000000000 };   // a departure each half second at 3 squares a second
const hex = (n) => n.toString(16).padStart(6, '0');
const idOf = (kind, n) => `${kind}-${hex(n)}`;

// each pair of grid cells one of `steps` apart, in step order and then cell order, each pair once
function pairsBy(steps) {
	const out = [], seen = new Set();
	for (const [dc, dr] of steps) for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) {
		const c2 = c + dc, r2 = r + dr;
		if (c2 < 0 || c2 >= COLS || r2 < 0 || r2 >= ROWS) continue;
		const a = r * COLS + c, b = r2 * COLS + c2, key = `${Math.min(a, b)},${Math.max(a, b)}`;
		if (!seen.has(key)) { seen.add(key); out.push([a, b]); }
	}
	return out;
}

export function capBoard() {
	const cells = [];
	for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) cells.push({ c, r, waypoint: (c + r) % 5 === 0 });
	const anchorId = (i) => idOf('node', i + 1);
	const links = pairsBy([[1, 0], [0, 1], [1, 1], [1, -1], [2, 0]]).slice(0, 2000);
	const pipes = pairsBy([[1, 0], [0, 1], [1, 1], [1, -1], [2, 0], [0, 2], [2, 1], [2, -1], [1, 2]]).slice(0, 4000);
	const ends = new Set(links.flat());
	const nodes = cells.map(({ c, r, waypoint }, i) => {
		const at = { x: -900 + c * PITCH, y: -480 + r * PITCH };
		if (!waypoint) return { id: anchorId(i), name: `d${i + 1}`, type: i % 2 ? 'host' : 'router', ...at, shape: 'circle' };
		return { id: anchorId(i), name: `w${i + 1}`, ...at, ...(ends.has(i) ? { spawn: { ...SPAWN } } : {}) };
	});
	const zones = [];
	for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) zones.push({ x: -930 + c * PITCH, y: -510 + r * PITCH, w: PITCH, h: PITCH });
	for (let r = 0; r < 7; r++) for (let c = 0; c < 7; c++) zones.push({ x: -930 + c * 4 * PITCH, y: -510 + r * 2 * PITCH, w: 2 * PITCH, h: 2 * PITCH });
	const groups = [];
	for (let i = 0; i + 1 < nodes.length; i += 2) groups.push([nodes[i].id, nodes[i + 1].id]);
	const ops = [
		...nodes.map((entity) => ({ op: 'put', kind: 'node', entity })),
		...zones.map((z, i) => ({ op: 'put', kind: 'zone', entity: { id: idOf('zone', i + 1), name: `z${i + 1}`, ...z } })),
		...links.map(([a, b], i) => ({ op: 'put', kind: 'link', entity: { id: idOf('link', i + 1), name: `l${i + 1}`, src: anchorId(a), dst: anchorId(b) } })),
		...groups.map((members, i) => ({ op: 'put', kind: 'group', entity: { id: idOf('group', i + 1), name: `g${i + 1}`, members } })),
	];
	return {
		about: 'PZ11\'s measure: every cap at once on the old frame -- 527 anchors, 576 zones, 2,000 links, 4,000 pipes, and 263 groups, the most 527 anchors hold -- in run mode, every spawner armed. Pan it at 3x by each gesture and read the footer\'s pan frame figure; its button resets it. Generated by tools/cap-board.mjs.',
		mode: 'run',
		ops,
		pipes: pipes.map(([a, b]) => [anchorId(a), anchorId(b), 'hand']),
	};
}

const SEEDS = new URL('../lab/seeds.json', import.meta.url);
if (process.argv[1] && new URL(`file://${process.argv[1]}`).href === import.meta.url) {
	const seeds = JSON.parse(fs.readFileSync(SEEDS, 'utf8'));
	const board = capBoard();
	if (process.argv.includes('--write')) {
		// every other board as it was written, tab-indented; this one an entity and a row of pipes to a line, so it reads and diffs by line
		const others = Object.fromEntries(Object.entries(seeds).filter(([k]) => k !== 'caps'));
		const rows = (list, per) => Array.from({ length: Math.ceil(list.length / per) }, (_, i) => `\t\t\t${list.slice(i * per, (i + 1) * per).map((x) => JSON.stringify(x)).join(', ')}`).join(',\n');
		const caps = `{\n\t\t"about": ${JSON.stringify(board.about)},\n\t\t"mode": ${JSON.stringify(board.mode)},\n\t\t"ops": [\n${rows(board.ops, 1)}\n\t\t],\n\t\t"pipes": [\n${rows(board.pipes, 4)}\n\t\t]\n\t}`;
		fs.writeFileSync(SEEDS, `${JSON.stringify(others, null, '\t').replace(/\n}$/, `,\n\t"caps": ${caps}\n}`)}\n`);
		console.log(`cap-board: lab/seeds.json's caps written -- ${board.ops.length} entities, ${board.pipes.length} pipes`);
	} else if (process.argv.includes('--check')) {
		const same = JSON.stringify(seeds.caps) === JSON.stringify(board);
		console.log(same ? 'cap-board: PASS -- lab/seeds.json\'s caps is the generator\'s' : 'cap-board: FAIL -- lab/seeds.json\'s caps differs; run node tools/cap-board.mjs --write');
		process.exitCode = same ? 0 : 1;
	} else console.log('usage: node tools/cap-board.mjs --write | --check');
}
