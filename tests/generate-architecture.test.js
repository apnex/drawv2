/*
H21.6 (U2; mission-kit AR1) -- THE CURRENT ARCHITECTURE IS DERIVED FROM THE CODE, AND THE GATE FAILS WHEN IT NO LONGER SAYS WHAT THE
CODE DECLARES. docs/ARCHITECTURE.md's structural sections are generated by tools/generate-architecture.mjs; its frame is authored.
*/
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const ROOT = path.resolve(import.meta.dirname, '..');
const TOOL = path.join(ROOT, 'tools/generate-architecture.mjs');
// the target document copied too, so no test ever writes the real one
const TARGET_COPY = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'draw-arch-target-')), 'ARCHITECTURE-TARGET.md');
fs.copyFileSync(path.join(ROOT, 'docs/ARCHITECTURE-TARGET.md'), TARGET_COPY);
const run = (...a) => spawnSync(process.execPath, [TOOL, '--target-doc', TARGET_COPY, ...a], { encoding: 'utf8' });
const copy = (edit) => {
	const f = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'draw-arch-')), 'ARCHITECTURE.md');
	fs.writeFileSync(f, edit(fs.readFileSync(path.join(ROOT, 'docs/ARCHITECTURE.md'), 'utf8')));
	return f;
};

test('H21.6: docs/ARCHITECTURE.md says what the code declares -- the control', () => {
	const r = run('--check');
	assert.equal(r.status, 0, r.stdout);
	const doc = fs.readFileSync(path.join(ROOT, 'docs/ARCHITECTURE.md'), 'utf8');
	assert.match(doc, /^---\ninstant: current\n/, 'the current instant, declared');
	for (const name of ['layers', 'kinds', 'canvas', 'compositions', 'doors', 'exceptions', 'gate', 'parts', 'part-divergence', 'justification']) assert.ok(doc.includes(`BEGIN GENERATED: architecture-${name}.`), name);
	assert.match(doc, /\| `link` \| the network \|/, 'the link is the network\'s kind, read from its row');
});

test('H21.6: a hand edit inside a generated region fails the check, naming the region; regenerating restores it', () => {
	const f = copy((d) => d.replace('| `link` | the network |', '| `link` | the core |'));
	const r = run('--check', '--doc', f);
	assert.equal(r.status, 1);
	assert.match(r.stdout, /no longer says what the code declares: \S+ kinds/);
	assert.equal(run('--doc', f).status, 0);
	assert.equal(run('--check', '--doc', f).status, 0, 'regenerated');
	assert.match(fs.readFileSync(f, 'utf8'), /\| `link` \| the network \|/);
});

test('H21.6: a document missing a region fails; the authored frame outside the regions is left as written', () => {
	const gone = copy((d) => d.replace(/<!-- BEGIN GENERATED: architecture-gate[\s\S]*?<!-- END GENERATED: architecture-gate -->/, ''));
	const r = run('--check', '--doc', gone);
	assert.equal(r.status, 1);
	assert.match(r.stdout, /has no region architecture-gate/);
	const framed = copy((d) => d.replace('## 1. Identity', '## 1. Identity, as authored'));
	assert.equal(run('--check', '--doc', framed).status, 0, 'prose outside a region is the author\'s');
});

// the part rules, driven over a parts declaration of the test's own, written from the real one with one fault planted
const partsWith = (edit) => {
	const f = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'draw-parts-')), 'parts.json');
	return import('../tools/layers.mjs').then(({ PARTS }) => { const p = structuredClone(PARTS); edit(p); fs.writeFileSync(f, JSON.stringify(p)); return f; });
};

test('H21.6: every product module is in exactly one part -- one left out, or in two, fails', async () => {
	let r = run('--check', '--parts', await partsWith((p) => { p.cli.modules = []; }));
	assert.equal(r.status, 1);
	assert.match(r.stdout, /cli\/draw\.mjs is in no part/);
	r = run('--check', '--parts', await partsWith((p) => { p.lattice.modules.push('kernel/theme.mjs'); }));
	assert.equal(r.status, 1);
	assert.match(r.stdout, /kernel\/theme\.mjs is in two parts/);
	r = run('--check', '--parts', await partsWith((p) => { p.lattice.modules.push('kernel/nowhere.mjs'); }));
	assert.match(r.stdout, /part lattice names kernel\/nowhere\.mjs, which is no product module/);
});

test('H21.6: an import the target does not allow must be carried by a live row -- uncarried, carried by a closed row, or carried stale, it fails', async () => {
	let r = run('--check', '--parts', await partsWith((p) => { delete p.network.carried; }));
	assert.equal(r.status, 1);
	assert.match(r.stdout, /part network imports devices, which the target's consumes do not allow, and no backlog row carries it/);
	r = run('--check', '--parts', await partsWith((p) => { p.network.carried.devices = 'B282x'; }));
	assert.equal(r.status, 1, 'a carrier that is no row');
	// REVIEW 2: a carrier is a bare B<n> -- not a frozen `from B<n>`, a ruling or a board item
	for (const bad of ['from B323', 'O1', 'H1.1']) {
		r = run('--check', '--parts', await partsWith((p) => { p.network.carried.devices = bad; }));
		assert.match(r.stdout, /is carried by a backlog row, written B<n>/, bad);
	}
	r = run('--check', '--parts', await partsWith((p) => { p.network.carried.devices = 'B323'; }));
	assert.match(r.stdout, /cites B323, which is CLOSED/, 'a carrier that is closed');
	r = run('--check', '--parts', await partsWith((p) => { p.network.consumes.push('devices'); }));
	assert.equal(r.status, 1);
	assert.match(r.stdout, /PARTS\.network\.carried names devices, but network imports it no more outside its consumes/, 'a carrier left after the import is allowed');
});

test("H21.6 review 2: the consumes are held to the target's section 4.3 -- a kind's ceiling, parts that exist, no cycle", async () => {
	let r = run('--check', '--parts', await partsWith((p) => { p.canvas.consumes.push('network'); delete p.canvas.carried.network; }));
	assert.equal(r.status, 1);
	assert.match(r.stdout, /part canvas \(host\) consumes network \(plugin\), which a host may not/, 'D1: the canvas names no plugin');
	r = run('--check', '--parts', await partsWith((p) => { p.lattice.consumes.push('devices'); }));
	assert.match(r.stdout, /part lattice \(core\) consumes devices \(plugin\), which a core may not/, 'N1: the core names no plugin');
	r = run('--check', '--parts', await partsWith((p) => { p.zones.consumes.push('nowhere'); }));
	assert.match(r.stdout, /part zones consumes nowhere, which is no part/);
	r = run('--check', '--parts', await partsWith((p) => { p.lattice.consumes.push('document'); }));
	assert.match(r.stdout, /the consumes form a cycle: (lattice -> document -> lattice|document -> lattice -> document)/);
	r = run('--check', '--parts', await partsWith((p) => { p.zones.consumes = '*'; }));
	assert.match(r.stdout, /part zones consumes any part, which only a composition root may/);
});

test("H21.6 review 2: a part's boundary cites the justification chain -- a `by` the target's section 2 does not cite fails", async () => {
	let r = run('--check', '--parts', await partsWith((p) => { p.zones.by = ['ZZ9']; }));
	assert.equal(r.status, 1);
	assert.match(r.stdout, /part zones is fixed by ZZ9, which the target's justification chain \(section 2\) does not cite/);
	r = run('--check', '--parts', await partsWith((p) => { p.zones.by = []; }));
	assert.match(r.stdout, /part zones cites nothing in the justification chain/);
	r = run('--check', '--parts', await partsWith((p) => { p.zones.by = ['O']; }));
	assert.match(r.stdout, /fixed by O,/, 'an id matches whole, not as the start of O1');
});

test('H21.6 review 2: each step of the current run time cites a test that exists', () => {
	let f = copy((d) => d.replace(/ \(`tests\/watchdog\.test\.js`\)/, ''));
	let r = run('--check', '--doc', f);
	assert.equal(r.status, 1);
	assert.match(r.stdout, /bullet "- \*\*A new revision:\*\*.*cites no test proving it/);
	f = copy((d) => d.replace('`tests/watchdog.test.js`', '`tests/no-such.test.js`'));
	r = run('--check', '--doc', f);
	assert.match(r.stdout, /cites tests\/no-such\.test\.js, which does not exist/);
});

test("H21.6 review 3: a door consumes no host, but for a consume a ruling in the chain names (`beyondKind`) -- the export's renderer, by H2", async () => {
	let r = run('--check', '--parts', await partsWith((p) => { p.hub.consumes.push('canvas'); }));
	assert.equal(r.status, 1, 'review 3 planted this: a server part consuming a browser part');
	assert.match(r.stdout, /part hub \(door\) consumes canvas \(host\), which a door may not/);
	r = run('--check', '--parts', await partsWith((p) => { delete p.export.beyondKind; }));
	assert.match(r.stdout, /part export \(door\) consumes renderer \(host\), which a door may not/);
	r = run('--check', '--parts', await partsWith((p) => { p.export.beyondKind.renderer = 'ZZ9'; }));
	assert.match(r.stdout, /beyondKind lets export consume renderer by ZZ9, which the target's justification chain \(section 2\) does not cite/);
	r = run('--check', '--parts', await partsWith((p) => { p.export.beyondKind.product = 'H2'; }));
	assert.match(r.stdout, /beyondKind names product, which its kind already allows/);
	r = run('--check', '--parts', await partsWith((p) => { p.rest.beyondKind = { canvas: 'H2' }; }));
	assert.match(r.stdout, /beyondKind names canvas, which rest does not consume/);
});

